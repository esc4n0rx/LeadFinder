'use strict';
const assert=require('node:assert/strict');
const fs=require('node:fs');
const vm=require('node:vm');
const context={window:{}};
vm.runInNewContext(fs.readFileSync('leadfinder/static/js/beautiful-ui.js','utf8'),context);
const ui=context.window.BeautifulUI;
const formatted=ui.richText('Benefício **claro**.\n\n1. Primeiro CTA\n2. Segundo ponto\n\n<img src=x onerror=alert(1)>');
assert.ok(formatted.includes('<strong>claro</strong>'));
assert.ok(formatted.includes('<ol><li>Primeiro CTA</li><li>Segundo ponto</li></ol>'));
assert.ok(!formatted.includes('<img'));
assert.ok(formatted.includes('&lt;img'));
const card=ui.recommendation({name:'<script>title</script>',body:'Olá {{empresa}} <img src=x>'},1,0);
assert.ok(!card.includes('<script>'));
assert.ok(card.includes('Olá {{empresa}} &lt;img'));
assert.ok(card.includes('data-ai-use="1"'));
assert.ok(ui.loading('Gerando',5).includes('role="status"'));
assert.ok(ui.loading('Gerando',5).includes('5s'));
assert.ok(ui.loading('<script>',5).includes('&lt;script&gt;'));
console.log('PASS Beautiful UI adapters: safe rich text, lists, draft cards, variables and loader.');
